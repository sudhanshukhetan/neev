/** Default assumptions object — keyed by id */
export const DEFAULT_ASSUMPTIONS = Object.fromEntries(
  ASSUMPTIONS_LIST.map((a) => [a.id, a.value])
);

/** Merge user overrides with defaults, clamping to min/max */
export function mergeAssumptions(overrides = {}) {
  const out = { ...DEFAULT_ASSUMPTIONS };
  for (const a of ASSUMPTIONS_LIST) {
    if (a.id in overrides) {
      const v = Number(overrides[a.id]);
      if (isFinite(v)) {
        out[a.id] = Math.min(a.max, Math.max(a.min, v));
      }
    }
  }
  return out;
}
